//
// It lives in PRODUCT code, not in the test, and that is a requirement of the work card rather than
// tidiness: "Один список управляет и тестом, и энфорсом — разойтись не могут". Two lists would drift
// the first time somebody crossed a line out of one of them — and the failure is silent in the worse
// direction. A surface removed from the ENFORCEMENT copy but left in the ratchet's copy is a surface
