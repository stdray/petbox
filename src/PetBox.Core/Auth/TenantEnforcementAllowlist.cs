//
// WHAT AN ENTRY MEANS: this surface predates the rule. The PEP passes it through untouched, and the
// ratchet does not demand a declaration for it. It is NOT a statement that the surface is fine — it
// is the debt this work item exists to pay off, made countable.
//
// IT ONLY EVER SHRINKS. A stale entry (a surface that has since been declared, or that no longer
// exists) fails AuthzDeclarationRatchetTests.StaleAllowlistEntries_AreDeleted, so the list cannot
// silently re-grant an exemption to whoever edits that surface next. A NEW surface never goes in
// here: it declares [TenantFrom]/[TenantExempt] like everything written after the rule.
//
// GENERATED BY THE INVENTORY, never by hand — AuthzDeclarationRatchetTests.TheInventory_IsMachineReadable
